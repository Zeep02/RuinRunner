"""Prepare source maps and C# only. Existing native PNGs are copied through Unity."""
from pathlib import Path
import json, hashlib

root=Path(__file__).resolve().parents[2]
review=root/'ArtDirection/Review-20261003/firearm-reload'
before=review/'before'
before.mkdir(parents=True,exist_ok=True)
files=['Runtime/Player/PlayerAnimationController.cs','Runtime/Items/OwnedEquipment.cs',
       'Runtime/Player/WeaponReloadFrames.cs','Runtime/Feedback/NativeHeroFrameCatalog.cs',
       'Runtime/Diagnostics/RuntimeSmokeTest.cs','Editor/NativeHeroAtlasPrebuild.cs']
for file in files:
    path=root/'Assets/RuinRunner'/file;target=before/path.name
    if target.exists(): raise RuntimeError(f'Preserve backup {target}')
    target.write_bytes(path.read_bytes())
data=json.loads((root/'ArtDirection/Review-20261003/weapon-reload/reload-import-v2.json').read_text(encoding='utf-8-sig'))
rows=[r for r in data['frames'] if 1<=r['clip']<=5]
old_ids=sorted({r['runtimeIndex'] for r in rows});remap={old:new for new,old in enumerate(old_ids)}
assert len(rows)==5*2*8*16*16 and len(old_ids)==7629
sources=[]
for old,new in remap.items():
    source=f'Assets/RuinRunner/ArtSources/Hero/WeaponReloadV2/{old:05d}.png'
    destination=f'Assets/RuinRunner/ArtSources/Hero/WeaponReloadV3/{new:05d}.png'
    sources.append(dict(source=source,destination=destination,
        pngSha256=hashlib.sha256((root/source).read_bytes()).hexdigest(),
        sourceMetaSha256=hashlib.sha256((root/(source+'.meta')).read_bytes()).hexdigest()))
for r in rows:
    r['previousIndex']=r['runtimeIndex'];r['runtimeIndex']=remap[r['runtimeIndex']]
    r['runtimePath']=sources[r['runtimeIndex']]['destination']
(review/'source-map.json').write_text(json.dumps(dict(scope='Five current ranged families; copied V2 native pixels, no new authoring or resampling. Bow excluded.',sources=sources,frames=rows),ensure_ascii=False,indent=2),encoding='utf-8')
cells=','.join(str(r['runtimeIndex']) for r in rows)
hands=','.join(f'new Vector2({r["grip"][0]}f,{r["grip"][1]}f)' for r in rows)
behind=','.join(str(r['handBehindBody']).lower() for r in rows)
code='''// Five current native reloads, exact carry/shot entries and original breathing/gait/head.
// Generated by Tools/Art/prepare_firearm_reload_20261003.py; PNG imports use Unity APIs.
using UnityEngine;
namespace RuinRunner
{
    public static class WeaponReloadFrames
    {
        public const string Root="External/SscaryMaleCombat/WeaponReloadV3";
        public const int UniqueSpriteCount=7629;
        public const int SampleCount=20480;
        static Sprite[] frames;
        static readonly int[] Cells={CELLS};
        static readonly Vector2[] Hands={HANDS};
        static readonly bool[] Behind={BEHIND};
        public static void Preload()
        {
            if(frames!=null)return;
            frames=new Sprite[UniqueSpriteCount];
            for(int i=0;i<frames.Length;i++)frames[i]=IndividualArt.Sprite(Root+"/"+i.ToString("D5"));
        }
        public static int Clip(WeaponFamily family)
        {
            switch(family)
            {
                case WeaponFamily.Crossbow:return 1;
                case WeaponFamily.Pistol:return 2;
                case WeaponFamily.Rifle:return 3;
                case WeaponFamily.Shotgun:return 4;
                case WeaponFamily.Cannon:return 5;
                default:throw new System.ArgumentOutOfRangeException(nameof(family));
            }
        }
        public static Sprite Sample(int clip,int entry,int direction,int variant,int key,out Vector2 hand,out bool behind)
        {
            if(clip<1||clip>5)throw new System.ArgumentOutOfRangeException(nameof(clip));
            Preload();
            int slot=((((clip-1)*2+Mathf.Clamp(entry,0,1))*8+Mathf.Clamp(direction,0,7))*16+Mathf.Clamp(variant,0,15))*16+Mathf.Clamp(key,0,15);
            hand=Hands[slot];behind=Behind[slot];return frames[Cells[slot]];
        }
    }
}
'''.replace('CELLS',cells).replace('HANDS',hands).replace('BEHIND',behind)
(root/'Assets/RuinRunner/Runtime/Player/WeaponReloadFrames.cs').write_text(code,encoding='utf-8')
pending=root/'ArtDirection/Review-20261003/weapon-reload/pending-runtime'
old=root/'ArtDirection/Review-20261003/weapon-reload/before'
for target in ['Runtime/Player/PlayerAnimationController.cs','Runtime/Items/OwnedEquipment.cs']:
    path=root/'Assets/RuinRunner'/target
    assert path.read_bytes()==(old/path.name).read_bytes(),f'Current source changed; merge manually: {path}'
    path.write_bytes((pending/path.name).read_bytes())
print(json.dumps(dict(samples=len(rows),unique=len(sources),bowSamples=0,review=str(review))))
