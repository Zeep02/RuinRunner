using System;
using System.IO;
using System.Text;
using System.Collections.Generic;
using UnityEditor;
using UnityEditor.U2D.Sprites;
using UnityEngine;
using Newtonsoft.Json.Linq;

public static class ImportSscaryThrust20261001
{
    const string Root="Assets/RuinRunner/Resources/Art/Pixel/Separated/External/SscaryMaleCombat/Thrust/";
    public static string Main()
    {
        if(Application.isPlaying)throw new Exception("Stop Play Mode");
        if(Directory.Exists(Root))throw new Exception("Existing import must be preserved");
        var data=JObject.Parse(File.ReadAllText("ArtDirection/Generated/SscaryMotion-20261001/thrust-v3/manifest.json",Encoding.UTF8));
        var unique=new Dictionary<string,int>();var paths=new List<string>();var cells=new int[864];var hands=new Vector2[864];var rows=new JArray();
        Directory.CreateDirectory(Root);
        foreach(var token in data["frames"])
        {
            var row=(JObject)token;string key=(string)row["pixelsSha256"];
            int index;if(!unique.TryGetValue(key,out index))
            {
                index=unique.Count;unique.Add(key,index);string path=Root+index.ToString("D2")+".png";
                File.Copy((string)row["path"],path);paths.Add(path);
            }
            int direction=Array.IndexOf(new[]{"up","right_up","right_down","down","left_down","left_up"},(string)row["direction"]);
            int slot=(direction*9+((int)row["gait"]+1))*16+(int)row["frame"];
            cells[slot]=index;hands[slot]=new Vector2((float)row["grip"][0],(float)row["grip"][1]);
            var adopted=(JObject)row.DeepClone();adopted["runtimePath"]=paths[index];adopted["runtimeIndex"]=index;rows.Add(adopted);
        }
        AssetDatabase.Refresh(ImportAssetOptions.ForceSynchronousImport);
        AssetDatabase.StartAssetEditing();
        try
        {
            foreach(var path in paths)
            {
                var imp=(TextureImporter)AssetImporter.GetAtPath(path);imp.textureType=TextureImporterType.Sprite;imp.spriteImportMode=SpriteImportMode.Single;
                imp.spritePixelsPerUnit=32;imp.filterMode=FilterMode.Point;imp.mipmapEnabled=false;imp.textureCompression=TextureImporterCompression.Uncompressed;
                imp.npotScale=TextureImporterNPOTScale.None;imp.wrapMode=TextureWrapMode.Clamp;imp.alphaIsTransparency=true;imp.isReadable=false;
                var setting=new TextureImporterSettings();imp.ReadTextureSettings(setting);setting.spriteMeshType=SpriteMeshType.FullRect;imp.SetTextureSettings(setting);
                AssetDatabase.WriteImportSettingsIfDirty(path);AssetDatabase.ImportAsset(path);
            }
        }finally{AssetDatabase.StopAssetEditing();}
        var factories=new SpriteDataProviderFactories();factories.Init();AssetDatabase.StartAssetEditing();
        try
        {
            foreach(var path in paths)
            {
                var imp=(TextureImporter)AssetImporter.GetAtPath(path);var provider=factories.GetSpriteEditorDataProviderFromObject(imp);provider.InitSpriteEditorDataProvider();
                var cap=provider.GetDataProvider<ISpriteFrameEditCapability>();if(cap==null||!cap.GetEditCapability().HasCapability(EEditCapability.EditPivot))throw new Exception("Pivot capability "+path);
                var rects=provider.GetSpriteRects();if(rects.Length!=1)throw new Exception(path);
                rects[0].alignment=SpriteAlignment.Custom;rects[0].pivot=new Vector2(.5f,22/64f);provider.SetSpriteRects(rects);provider.Apply();
                AssetDatabase.WriteImportSettingsIfDirty(path);AssetDatabase.ImportAsset(path);
            }
        }finally{AssetDatabase.StopAssetEditing();}
        foreach(var path in paths){var sprite=AssetDatabase.LoadAssetAtPath<Sprite>(path);if(sprite==null||sprite.rect.width!=48||sprite.rect.height!=64||sprite.pixelsPerUnit!=32||sprite.pivot!=new Vector2(24,22))throw new Exception("Import geometry "+path);}
        var code=new StringBuilder("// Authored native thrust joints + original gait composition. Generated by ImportSscaryThrust20261001.\nusing UnityEngine;\nnamespace RuinRunner\n{\n public static class SscaryThrustFrames\n {\n");
        code.Append("  public const string Root=\"External/SscaryMaleCombat/Thrust\";\n  public const int UniqueSpriteCount=").Append(paths.Count).Append(";\n  public const int KeyCount=16;\n  private static Sprite[] frames;\n  private static readonly int[] DirectionRows={0,1,2,2,3,4,4,5};\n");
        code.Append("  private static readonly float[] Phases={");foreach(var p in data["phases"])code.Append(((float)p).ToString(System.Globalization.CultureInfo.InvariantCulture)).Append("f,");code.Append("};\n");
        code.Append("  private static readonly int[] Cells={");foreach(var cell in cells)code.Append(cell).Append(',');code.Append("};\n");
        code.Append("  private static readonly Vector2[] Hands={");foreach(var h in hands)code.Append("new Vector2(").Append(h.x.ToString(System.Globalization.CultureInfo.InvariantCulture)).Append("f,").Append(h.y.ToString(System.Globalization.CultureInfo.InvariantCulture)).Append("f),");code.Append("};\n");
        code.Append("  public static void Preload(){if(frames==null)frames=IndividualArt.Frames(Root,UniqueSpriteCount);}\n  public static int PhaseIndex(float p){for(int i=KeyCount-1;i>=0;i--)if(p>=Phases[i])return i;return 0;}\n  public static Sprite Sample(int direction,int gait,int key,out Vector2 grip){Preload();int slot=(DirectionRows[Mathf.Clamp(direction,0,7)]*9+Mathf.Clamp(gait+1,0,8))*KeyCount+Mathf.Clamp(key,0,KeyCount-1);grip=Hands[slot];return frames[Cells[slot]];}\n }\n}\n");
        File.WriteAllText("Assets/RuinRunner/Runtime/Player/SscaryThrustFrames.cs",code.ToString(),new UTF8Encoding(false));
        File.WriteAllText("ArtDirection/Review-20261001/hero-thrust/native-import.json",new JObject{{"uniqueSprites",paths.Count},{"sampleSlots",864},{"standUniquePoses",data["standUniquePoses"]},{"scope","Only thrust. Six views / fixed canvas and foot pivot. Duplicate phase or gait images share one sprite; they are not counted as authored poses. Face/pack preserved; source and native modification records below."},{"frames",rows}}.ToString(),new UTF8Encoding(false));
        AssetDatabase.SaveAssets();AssetDatabase.Refresh();return paths.Count+" unique native sprites imported; 864 phase/gait slots share duplicate sprites; fixed (24,22)/32PPU, Point, no mip/compression.";
    }
}
